; HELLO FOR NTV4004: PRINT A MESSAGE ON THE CONSOLE, ROM PORT 15.
; EACH CHARACTER GOES OUT AS TWO NIBBLES, HIGH FIRST. LOWERCASE
; LETTERS ARE NUMBERS BECAUSE MAC4 READS ONLY UPPERCASE SOURCE.
        FIM 14,0F0H     ; R14R15 SELECTS ROM PORT 15
        SRC 14
        FIM 0,MSG       ; R0R1 POINTS INTO THE MESSAGE ON THIS PAGE
NEXT:   FIN 2           ; R2R3 = THE CHARACTER AT R0R1
        LD 2
        JCN 0CH,SHOW    ; HIGH NIBBLE NOT ZERO: PRINT IT
        LD 3
        JCN 4,DONE      ; A ZERO BYTE ENDS THE MESSAGE
SHOW:   LD 2
        WRR
        LD 3
        WRR
        ISZ 1,NEXT      ; NEXT CHARACTER
        INC 0
        JUN NEXT
DONE:   JUN DONE
MSG:    DB 48H,65H,6CH,6CH,6FH,20H,66H,72H
        DB 6FH,6DH,20H,74H,68H,65H,20H,49H
        DB 6EH,74H,65H,6CH,20H,34H,30H,30H
        DB 34H,21H,0DH,0
        END
